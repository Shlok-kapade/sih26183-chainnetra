async def run_baseline(name: str, graph: dict, seed_amount: Decimal, timeline_events: list) -> dict:
    """Run a single baseline against the fixture."""
    trace = FixtureTracePort(graph=graph)
    budget = FixtureBudgetPort(limit=500)
    clock = FixtureClockPort()
    notify = FixtureNotifyPort()

    runner = ReplayRunner(
        case_id='synth_case',
        events=timeline_events,
        trace=trace, clock=clock,
        budget=budget, notify=notify,
        seed_amount=seed_amount, K=5,
    )
    result = await runner.run(baseline=name)
    return {
        'baseline': name,
        'ev_total': float(result.final_ev_total),
        'time_to_first_action_hours': result.time_to_first_action_hours,
        'api_calls': result.api_calls_used,
        'act_now_triggered': result.act_now_triggered,
        'plans_computed': result.plans_computed,
    }

def write_results(results: list, output_path: str):
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    lines = [
        '# ADDON_RESULTS.md — FOT Replay Evaluation',
        '',
        '> All data is SYNTHETIC. Numbers generated by eval script only. Priors are ILLUSTRATIVE.',
        '',
        '## B. FOT Replay Results',
        '',
        '| Baseline | EV Total | Time to First Action (h) | API Calls | Act-Now Triggered |',
        '|----------|----------|--------------------------|-----------|-------------------|',
    ]
    for r in results:
        lines.append(
            f"| {r['baseline']} | {r['ev_total']:.2f} | {r['time_to_first_action_hours']} | {r['api_calls']} | {r['act_now_triggered']} |"
        )
    lines += [
        '',
        '## Limitations',
        '- All results use SYNTHETIC timelines — not real case data.',
        '- Priors (p_success, latency) are ILLUSTRATIVE assumptions.',
        '- EV values are estimates; real recovery depends on VASP cooperation and legal process.',
    ]
    with open(output_path, 'w') as f:
        f.write('\n'.join(lines))
    print(f'Results written to {output_path}')

async def main():
    from scripts.addon.synth_timeline import generate_d9_timeline, generate_rapid_exit_timeline
    seed = Decimal('50000')
    timeline = generate_d9_timeline(seed_amount=seed)

    baselines = ['B1_trace_complete', 'B2_BFS_first_exchange', 'B3_M3_guided', 'B4_FOT']
    results = []
    for b in baselines:
        r = await run_baseline(b, SYNTH_GRAPH_WITH_EXIT, seed, timeline)
        results.append(r)
        print(f"{b}: ev={r['ev_total']:.2f}, api_calls={r['api_calls']}")

    write_results(results, 'docs/evaluation/ADDON_RESULTS.md')

if __name__ == '__main__':
    asyncio.run(main())
