"""
M1 Eval Script — generates docs/evaluation/RESULTS.md
======================================================
Usage: backend/.venv/bin/python backend/ml/eval/eval_m1.py
       (also called by: make eval)

Loads the latest M1 (and M1b if available) artifacts, runs evaluation,
and writes docs/evaluation/RESULTS.md with tables and honest commentary.
All numbers come from metrics.json — nothing is hand-typed.
"""
from __future__ import annotations

import json
import sys
from datetime import datetime, timezone
from pathlib import Path

PROJECT_ROOT = Path(__file__).parents[3]
sys.path.insert(0, str(PROJECT_ROOT / "backend"))

RESULTS_PATH = PROJECT_ROOT / "docs" / "evaluation" / "RESULTS.md"
ARTIFACTS_ROOT = PROJECT_ROOT / "ml" / "artifacts"


def load_metrics(model_id: str) -> dict | None:
    base = ARTIFACTS_ROOT / model_id
    if not base.exists():
        return None
    versions = sorted([v.name for v in base.iterdir() if v.is_dir() and v.name != "latest"], reverse=True)
    if not versions:
        return None
    metrics_path = base / versions[0] / "metrics.json"
    if not metrics_path.exists():
        return None
    with open(metrics_path) as f:
        return json.load(f)


def load_config(model_id: str) -> dict | None:
    base = ARTIFACTS_ROOT / model_id
    if not base.exists():
        return None
    versions = sorted([v.name for v in base.iterdir() if v.is_dir() and v.name != "latest"], reverse=True)
    if not versions:
        return None
    config_path = base / versions[0] / "config.json"
    if not config_path.exists():
        return None
    with open(config_path) as f:
        return json.load(f)


def fmt(val: object, digits: int = 3) -> str:
    if val is None or (isinstance(val, float) and val != val):
        return "n/a"
    if isinstance(val, float):
        return f"{val:.{digits}f}"
    if val == "n/a":
        return "n/a"
    return str(val)


def generate_results() -> str:
    ts = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    m1 = load_metrics("m1")
    m1b = load_metrics("m1b")

    lines = []
    lines.append("# ChainNetra — Evaluation Results\n")
    lines.append(f"> Generated: {ts}  ")
    lines.append("> Source: `make eval` → `backend/ml/eval/eval_m1.py`\n")
    lines.append("> **All numbers are computed from held-out test data. No hand-typed metrics.**\n")

    # ---------- DATA WARNING ----------
    lines.append("## ⚠️  Critical Caveat on Current Metrics\n")
    lines.append(
        "M1 is currently trained on **synthetic data** generated by `scripts/synth_laundering.py` "
        "because real labeled addresses are insufficient (< 10 per class). "
        "The synthetic distribution intentionally differs from the real-world distribution. "
        "**Metrics below reflect synthetic-data performance only and WILL NOT reflect "
        "real-world investigative accuracy until real labeled data is added.**\n"
    )
    lines.append(
        "To improve: add real labeled addresses to `data/labels/*.csv` (OFAC full SDN list, "
        "exchange PoR lists, community label repos) and re-run `make train-m1 && make eval`.\n"
    )

    # ---------- M1 ----------
    lines.append("---\n## M1 — Address Role Classifier\n")

    if m1 is None:
        lines.append("**Status: NOT TRAINED** — run `make train-m1` first.\n")
    else:
        ts_split = m1.get("temporal_split", {})
        ds = m1.get("dataset", {})

        lines.append("**Model**: LightGBM + isotonic calibration  ")
        lines.append(f"**Dataset**: {ds.get('n_samples', '?')} samples, {ds.get('n_features', '?')} features  ")
        lines.append(f"**Split**: {ds.get('n_train', '?')} train / {ds.get('n_cal', '?')} cal / {ds.get('n_test', '?')} test\n")
        lines.append(f"> Data note: {ds.get('note', '')}\n")

        # Baseline comparison
        lines.append("### Baseline Comparison (Temporal Split)\n")
        lines.append("| Model | Macro-F1 |")
        lines.append("|-------|----------|")
        lines.append(f"| Rules-only heuristic | {fmt(ts_split.get('rules_baseline_macro_f1'))} |")
        lines.append(f"| Logistic Regression | {fmt(ts_split.get('lr_baseline_macro_f1'))} |")
        lines.append(f"| **LightGBM (calibrated)** | **{fmt(ts_split.get('lgbm_macro_f1'))}** |\n")

        # Calibration
        lines.append("### Calibration\n")
        lines.append("| Metric | Value |")
        lines.append("|--------|-------|")
        lines.append(f"| ECE before calibration | {fmt(ts_split.get('ece_before_calibration'))} |")
        lines.append(f"| ECE after isotonic cal | {fmt(ts_split.get('ece_after_calibration'))} |")
        lines.append("| Acceptance threshold | < 0.10 |")
        ece = ts_split.get("ece_after_calibration", 1.0)
        if isinstance(ece, float) and ece < 0.10:
            lines.append(f"\n✅ ECE = {fmt(ece)} meets acceptance criterion (< 0.10).")
        else:
            lines.append(f"\n⚠️  ECE = {fmt(ece)} does NOT meet acceptance criterion (< 0.10). Investigate calibration.")
        lines.append("")

        # Per-class PR-AUC
        lines.append("### Per-Class PR-AUC (LightGBM, calibrated)\n")
        lines.append("| Class | LightGBM PR-AUC | LogReg PR-AUC |")
        lines.append("|-------|-----------------|---------------|")
        lgbm_pr = ts_split.get("lgbm_pr_auc_per_class", {})
        lr_pr = ts_split.get("lr_pr_auc_per_class", {})
        from app.ml.features import ROLE_CLASSES  # noqa
        for cls in ROLE_CLASSES:
            lines.append(f"| {cls} | {fmt(lgbm_pr.get(cls))} | {fmt(lr_pr.get(cls))} |")
        lines.append("")

        # Classification report
        lines.append("### Classification Report (LightGBM, calibrated, temporal test set)\n")
        cr = m1.get("classification_report_lgbm", {})
        lines.append("| Class | Precision | Recall | F1 | Support |")
        lines.append("|-------|-----------|--------|----|---------|")
        for cls in ROLE_CLASSES:
            d = cr.get(cls, {})
            lines.append(
                f"| {cls} | {fmt(d.get('precision'))} | {fmt(d.get('recall'))} | "
                f"{fmt(d.get('f1-score'))} | {d.get('support', '?')} |"
            )
        lines.append(f"| **macro avg** | {fmt(cr.get('macro avg', {}).get('precision'))} | "
                     f"{fmt(cr.get('macro avg', {}).get('recall'))} | "
                     f"{fmt(cr.get('macro avg', {}).get('f1-score'))} | {cr.get('macro avg', {}).get('support', '?')} |")
        lines.append("")

        # SHAP
        top_shap = m1.get("shap_top_features", {})
        if top_shap:
            lines.append("### Top-15 SHAP Features (mean |SHAP| across all classes)\n")
            lines.append("| Rank | Feature | Mean |SHAP| |")
            lines.append("|------|---------|-------------|")
            for rank, (fname, fval) in enumerate(list(top_shap.items())[:15], 1):
                lines.append(f"| {rank} | {fname} | {fmt(fval, 4)} |")
            lines.append("")

        # Leave-one-class-out
        loeo = m1.get("leave_one_class_out", {})
        if loeo:
            lines.append("### Leave-One-Class-Out Results\n")
            lines.append(
                "> Note: With synthetic data this is a proxy for leave-one-exchange-out. "
                "Real exchange-level evaluation requires exchange-annotated real data.\n"
            )
            lines.append("| Withheld Class | Test N | Recall on Withheld |")
            lines.append("|----------------|--------|--------------------|")
            for cls, res in loeo.items():
                lines.append(f"| {cls} | {res.get('withheld_n_test', '?')} | {fmt(res.get('recall_withheld'))} |")
            lines.append("")

    # ---------- M1b ----------
    lines.append("---\n## M1b — BTC Illicit Transaction Scorer (Elliptic Dataset)\n")

    if m1b is None:
        elliptic_present = (PROJECT_ROOT / "data" / "raw" / "elliptic" / "elliptic_txs_features.csv").exists()
        if not elliptic_present:
            lines.append("**Status: BLOCKED — Elliptic dataset not found.**\n")
            lines.append("### Required Action\n")
            lines.append(
                "Download the Elliptic Bitcoin Dataset and place it at:\n"
                "```\n"
                "data/raw/elliptic/elliptic_txs_features.csv\n"
                "data/raw/elliptic/elliptic_txs_classes.csv\n"
                "data/raw/elliptic/elliptic_txs_edgelist.csv\n"
                "```\n"
                "Source: https://www.kaggle.com/datasets/ellipticco/elliptic-data-set (CC BY 4.0)\n\n"
                "Then run:\n"
                "```bash\n"
                "backend/.venv/bin/python backend/ml/train/train_m1b.py\n"
                "make eval\n"
                "```\n"
            )
        else:
            lines.append("**Status: Dataset present but not yet trained.** Run `backend/.venv/bin/python backend/ml/train/train_m1b.py`\n")
    else:
        lines.append(f"**Dataset**: {m1b.get('dataset', '?')}  ")
        lines.append(f"**Split**: {m1b.get('split', '?')}  ")
        lines.append(f"**Train N**: {m1b.get('n_train', '?')} | **Test N**: {m1b.get('n_test', '?')}\n")
        lines.append("| Metric | Value |")
        lines.append("|--------|-------|")
        lines.append(f"| Illicit PR-AUC | {fmt(m1b.get('illicit_pr_auc'))} |")
        lines.append(f"| Illicit F1     | {fmt(m1b.get('illicit_f1'))} |")
        lines.append(f"| Illicit Precision | {fmt(m1b.get('illicit_precision'))} |")
        lines.append(f"| Illicit Recall    | {fmt(m1b.get('illicit_recall'))} |")
        lines.append(f"\n> {m1b.get('note', '')}\n")

    # ---------- Acceptance criteria summary ----------
    lines.append("---\n## Acceptance Criteria Checklist\n")
    lines.append("| Criterion | Status |")
    lines.append("|-----------|--------|")

    if m1:
        ts_split = m1.get("temporal_split", {})
        lgbm_f1 = ts_split.get("lgbm_macro_f1", 0)
        lr_f1 = ts_split.get("lr_baseline_macro_f1", 1)
        rules_f1 = ts_split.get("rules_baseline_macro_f1", 1)
        ece = ts_split.get("ece_after_calibration", 1.0)
        beats_baselines = isinstance(lgbm_f1, float) and isinstance(lr_f1, float) and lgbm_f1 > lr_f1 and lgbm_f1 > rules_f1
        ece_ok = isinstance(ece, float) and ece < 0.10
        loeo_present = bool(m1.get("leave_one_class_out"))
        shap_present = bool(m1.get("shap_top_features"))
        lines.append(f"| LightGBM beats logistic + rules on macro-F1 (temporal split) | {'✅' if beats_baselines else '❌'} |")
        lines.append(f"| ECE < 0.10 after calibration | {'✅' if ece_ok else f'❌ (ECE={fmt(ece)})'} |")
        lines.append(f"| Leave-one-class-out table included | {'✅' if loeo_present else '❌'} |")
        lines.append(f"| SHAP top-k features stored | {'✅' if shap_present else '❌'} |")
        lines.append("| Model card documents label bias + FP modes | ✅ |")
        lines.append("| Trained on real data (not only synthetic) | ❌ — add real labels to data/labels/ |")
    else:
        lines.append("| M1 trained | ❌ — run `make train-m1` |")

    lines.append(f"| M1b (Elliptic) | {'✅' if m1b else '❌ — dataset required (see above)'} |")
    lines.append("")

    # ---------- M3 section ----------
    lines.append("---\n## M3 — Guided Tracing Policy\n")

    m3 = load_metrics("m3")
    if m3 is None:
        lines.append("**Status: NOT TRAINED** — run `make train-m3` first.\n")
    else:
        lines.append("**Model**: LightGBM binary classifier + isotonic calibration  ")
        lines.append(f"**Train N**: {m3.get('n_train', '?')} | **Test N**: {m3.get('n_test', '?')}  ")
        lines.append(f"**Positive fraction (test)**: {m3.get('n_positive_test', '?')} / {m3.get('n_test', '?')}  ")
        lines.append("")
        lines.append("> ⚠️ Trained on synthetic graphs only (synth_laundering.py). See MODEL_CARD.md for ground-truth bias caveat.\n")
        lines.append("### M3 Classifier Metrics (synthetic test set)\n")
        lines.append("| Metric | Value |")
        lines.append("|--------|-------|")
        lines.append(f"| PR-AUC | {fmt(m3.get('pr_auc'))} |")
        lines.append(f"| ROC-AUC | {fmt(m3.get('roc_auc'))} |")
        lines.append(f"| F1 @ threshold=0.5 | {fmt(m3.get('f1_at_threshold_0_5'))} |")
        lines.append(f"| ECE | {fmt(m3.get('ece'))} |")

        # Run benchmark and include recall table
        lines.append("")
        lines.append("### recall@B — Policy Benchmark (held-out synthetic seeds)\n")
        try:
            from ml.eval.benchmark_m3 import format_recall_table, run_benchmark  # noqa: PLC0415
            print("  Running M3 benchmark (this may take ~30s) …")
            bench = run_benchmark(n_test=20)
            lines.append(format_recall_table(bench))
            lines.append(f"*{bench.get('n_test_traces', '?')} held-out trace graphs.*  ")

            # Per-policy CTFE
            results = bench.get("results", {})
            budgets = bench.get("budgets", [])
            lines.append("")
            lines.append("#### Mean calls-to-first-exit by policy\n")
            lines.append("| Policy | Mean calls-to-first-exit |")
            lines.append("|--------|--------------------------|")
            for pol in bench.get("policies", []):
                ctfe_vals = [
                    results[pol][b]["mean_calls_to_first_exit"]
                    for b in budgets
                    if results[pol][b]["mean_calls_to_first_exit"] is not None
                ]
                val = f"{sum(ctfe_vals)/len(ctfe_vals):.1f}" if ctfe_vals else "N/A"
                lines.append(f"| {'**M3-guided**' if pol == 'guided' else pol} | {val} |")

        except Exception as exc:
            lines.append(f"*(Benchmark unavailable: {exc})*\n")

        lines.append("")
        lines.append("### ⚠️ Ground-Truth Bias Caveat\n")
        lines.append(
            "Recall is measured only against **labeled** VASP addresses in `data/labels/*.csv`. "
            "Unlabeled exchanges are invisible to evaluation: the engine will find more exits "
            "in practice, but they cannot be verified against ground truth without broader labeling. "
            "**Published recall figures are lower bounds on true investigative coverage.** "
            "Additionally, all results are from synthetic graphs (generators match training distribution); "
            "real-world graphs have partial topology, more diverse structures, and API budget constraints "
            "that differ from simulation."
        )
        lines.append("")

    lines.append("---\n*End of RESULTS.md*\n")

    return "\n".join(lines)


def main() -> None:
    RESULTS_PATH.parent.mkdir(parents=True, exist_ok=True)
    content = generate_results()
    RESULTS_PATH.write_text(content)
    print(f"✓ RESULTS.md written to: {RESULTS_PATH}")
    # Print summary to stdout
    for line in content.split("\n")[:50]:
        print(line)


if __name__ == "__main__":
    main()
